#!/usr/bin/env python3
"""Generate instruction tests (Xenia's .s format) for the instructions our XenonRecomp patch
0011 adds for Black Ops II. Modelled on the Deadpool project's tests/gen_instr_tests.py, which in
turn follows SpeedBreaker's.

Expected values come from an independent Python model of the PowerPC semantics, never from the
recompiler, so a codegen bug can't agree with itself. Vectors are written as four big-endian
words, element 0 first, as the guest sees them. LLVM can't assemble VMX128, so vpkshss128 is
emitted as `.long` with the encoding computed here.

    python3 -I tests/gen_bo2_instr_tests.py     # writes tests/instr/bo2_*.s
"""
import math
import os
import random
import struct

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "instr")
rng = random.Random(0x415608C3)
M64 = (1 << 64) - 1
M32 = (1 << 32) - 1
MEM = 0x1000


def write(name, tests):
    path = os.path.join(OUT, f"bo2_{name}.s")
    with open(path, "w") as f:
        f.write("# Generated by tests/gen_bo2_instr_tests.py (independent Python model). Do not edit.\n\n")
        for i, (ins, body, outs) in enumerate(tests, 1):
            f.write(f"test_bo2_{name}_{i}:\n")
            for line in ins:
                f.write(f"  #_ {line}\n")
            for line in body:
                f.write(f"  {line}\n")
            for line in outs:
                f.write(f"  #_ {line}\n")
            f.write("\n")
    return len(tests)


def hx(v):
    return f"0x{v:X}"


def mem(addr, data):
    return f"{addr:08X} " + " ".join(f"{b:02X}" for b in data)


# --- vector helpers -------------------------------------------------------------------------

def vec(ws):
    return "[" + ", ".join(f"{w:08X}" for w in ws) + "]"


def to_bytes(ws):
    return b"".join(struct.pack(">I", w) for w in ws)


def from_bytes(b):
    return [struct.unpack(">I", b[i:i + 4])[0] for i in range(0, 16, 4)]


def vx128(xop, vd, va, vb):
    """VX128 (opcode 5) encoding, per XenonRecomp's disassembler (insert_vds128/va128/vb128)."""
    w = (5 << 26) | (xop & 0x3D0)
    w |= ((vd & 0x60) >> 3) | ((vd & 0x1F) << 21)
    w |= ((va & 0x40) << 4) | (va & 0x20) | ((va & 0x1F) << 16)
    w |= ((vb & 0x60) >> 5) | ((vb & 0x1F) << 11)
    return w


def rand_bytes():
    pool = (0x00, 0x01, 0x7F, 0x80, 0x81, 0xFF, 0xFE, 0x40)
    return bytes(rng.choice(pool) if rng.random() < 0.5 else rng.getrandbits(8) for _ in range(16))


def rand_words():
    pool = (0, 1, 0x7FFFFFFF, 0x80000000, 0xFFFFFFFF, 0xFFFFFFFE)
    return [rng.choice(pool) if rng.random() < 0.5 else rng.getrandbits(32) for _ in range(4)]


def s8(b):
    return b - 256 if b & 0x80 else b


def clamp(x, lo, hi):
    return max(lo, min(hi, x))


def binary_vec_tests(mnemonic, model, gen, count=10):
    tests = []
    for _ in range(count):
        a, b = gen(), gen()
        r = model(a, b)
        tests.append(([f"REGISTER_IN v1 {vec(a)}", f"REGISTER_IN v2 {vec(b)}"],
                      [f"{mnemonic} v3, v1, v2", "blr"], [f"REGISTER_OUT v3 {vec(r)}"]))
    return tests


def bytewise(fn):
    def model(a, b):
        ab, bb = to_bytes(a), to_bytes(b)
        return from_bytes(bytes(fn(x, y) & 0xFF for x, y in zip(ab, bb)))
    return model


def gen_bytes():
    return from_bytes(rand_bytes())


# --- the instructions -----------------------------------------------------------------------

def vsubsbs_tests():
    return binary_vec_tests("vsubsbs", bytewise(lambda x, y: clamp(s8(x) - s8(y), -128, 127)), gen_bytes)


def vmaxsb_tests():
    return binary_vec_tests("vmaxsb", bytewise(lambda x, y: x if s8(x) >= s8(y) else y), gen_bytes)


def vsrb_tests():
    return binary_vec_tests("vsrb", bytewise(lambda x, y: x >> (y & 7)), gen_bytes)


def vsubuws_tests():
    return binary_vec_tests("vsubuws", lambda a, b: [max(x - y, 0) for x, y in zip(a, b)], rand_words)


def vcmpgtuw_tests():
    return binary_vec_tests("vcmpgtuw", lambda a, b: [M32 if x > y else 0 for x, y in zip(a, b)], rand_words)


def vsl_tests():
    tests = []
    for sh in range(8):
        a = rand_words()
        value = (int.from_bytes(to_bytes(a), "big") << sh) & ((1 << 128) - 1)
        r = from_bytes(value.to_bytes(16, "big"))
        b = from_bytes(bytes([sh]) * 16)
        tests.append(([f"REGISTER_IN v1 {vec(a)}", f"REGISTER_IN v2 {vec(b)}"],
                      ["vsl v3, v1, v2", "blr"], [f"REGISTER_OUT v3 {vec(r)}"]))
    return tests


def vpkshss128_tests():
    tests = []
    pool = (0, 1, 0x7F, 0x80, 0xFF7F, 0xFF80, 0x7FFF, 0x8000, 0xFFFF, 0x0100)
    for _ in range(10):
        a = from_bytes(struct.pack(">8H", *[rng.choice(pool) for _ in range(8)]))
        b = from_bytes(struct.pack(">8H", *[rng.choice(pool) for _ in range(8)]))
        halves = struct.unpack(">8h", to_bytes(a)) + struct.unpack(">8h", to_bytes(b))
        r = from_bytes(struct.pack(">16b", *[clamp(h, -128, 127) for h in halves]))
        tests.append(([f"REGISTER_IN v1 {vec(a)}", f"REGISTER_IN v2 {vec(b)}"],
                      [f".long 0x{vx128(512, 3, 1, 2):08X}  # vpkshss128 v3, v1, v2", "blr"],
                      [f"REGISTER_OUT v3 {vec(r)}"]))
    return tests


def vrfip_tests():
    # vrfip and vrfip128 share one implementation; LLVM can only assemble the AltiVec form.
    tests = []
    for xs in ((1.5, -1.5, 2.0, 0.25), (-0.75, 3.0000002, -1e30, 1e30), (0.0, -2.5, 7.999, -7.999)):
        a = [struct.unpack(">I", struct.pack(">f", x))[0] for x in xs]
        # Rounding keeps the sign, so ceil(-0.75) is -0.0.
        r = [struct.unpack(">I", struct.pack(">f", math.copysign(float(math.ceil(x)), x)))[0] for x in xs]
        tests.append(([f"REGISTER_IN v1 {vec(a)}"], ["vrfip v3, v1", "blr"], [f"REGISTER_OUT v3 {vec(r)}"]))
    return tests


def lhbrx_tests():
    tests = []
    for disp in (0, 2, 6, 14):
        data = bytes(rng.getrandbits(8) for _ in range(2))
        base = MEM + 0x40
        ins = [f"REGISTER_IN r4 {hx(base)}", f"REGISTER_IN r5 {disp}", f"MEMORY_IN {mem(base + disp, data)}"]
        tests.append((ins, ["lhbrx r3, r4, r5", "blr"],
                      [f"REGISTER_OUT r3 {hx(int.from_bytes(data, 'little'))}", f"REGISTER_OUT r4 {hx(base)}"]))
    return tests


def ldux_tests():
    tests = []
    for disp in (0, 8, 16, -8):
        data = bytes(rng.getrandbits(8) for _ in range(8))
        base = MEM + 0x40
        ea = base + disp
        ins = [f"REGISTER_IN r4 {hx(base)}", f"REGISTER_IN r5 {hx(disp & M64)}", f"MEMORY_IN {mem(ea, data)}"]
        tests.append((ins, ["ldux r3, r4, r5", "blr"],
                      [f"REGISTER_OUT r3 {hx(int.from_bytes(data, 'big'))}", f"REGISTER_OUT r4 {hx(ea)}"]))
    return tests


def stvebx_tests():
    tests = []
    for off in (0, 3, 9, 15):
        v = from_bytes(rand_bytes())
        before = bytes(16)
        after = bytearray(before)
        after[off] = to_bytes(v)[off]
        tests.append(([f"REGISTER_IN v3 {vec(v)}", f"REGISTER_IN r4 {hx(MEM)}", f"REGISTER_IN r5 {off}",
                       f"MEMORY_IN {mem(MEM, before)}"],
                      ["stvebx v3, r4, r5", "blr"], [f"MEMORY_OUT {mem(MEM, bytes(after))}"]))
    return tests


def main():
    os.makedirs(OUT, exist_ok=True)
    for f in os.listdir(OUT):
        if f.startswith("bo2_") and f.endswith(".s"):
            os.remove(os.path.join(OUT, f))
    n = 0
    n += write("vsubsbs", vsubsbs_tests())
    n += write("vmaxsb", vmaxsb_tests())
    n += write("vsrb", vsrb_tests())
    n += write("vsubuws", vsubuws_tests())
    n += write("vcmpgtuw", vcmpgtuw_tests())
    n += write("vsl", vsl_tests())
    n += write("vpkshss128", vpkshss128_tests())
    n += write("vrfip", vrfip_tests())
    n += write("lhbrx", lhbrx_tests())
    n += write("ldux", ldux_tests())
    n += write("stvebx", stvebx_tests())
    print(f"wrote {n} tests to {OUT}")


if __name__ == "__main__":
    main()
