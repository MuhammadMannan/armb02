#!/usr/bin/env python3
"""Find secondary entry points: code addresses the game can reach indirectly that XenonRecomp
does not know as function starts.

Adapted from SpeedBreaker's survey/find_entry_points.py. Candidates are code addresses
  - stored in data sections (vtables, callback tables, function-pointer fields), or
  - materialised in code with `lis` + `addi`/`ori`,
that are not known function starts, not switch-case labels, and look like an entry
(preceded by `blr`, an unconditional `b`, or zero padding). Such an address shares a body with
a neighbouring function; XenonRecomp (SpeedBreaker patch 0003) emits it as an extra entry.

The list replaces the block between the markers in the config's [main] section.
Standard library only. Run in isolated mode:

    python3 -I scripts/find_entry_points.py --image orig/xbox360/image/image.bin --base 0x82000000 \
        --text 0x823B0000:0x8351182C --data 0x82000600:0x8233AC04 --data 0x83525C00:0x836F95F8 \
        --pdata 0x8233AE00:0x823A7700 --mapping generated/ppc/ppc_func_mapping.cpp \
        --switch-tables config/deadpool_switch_tables.toml --config config/deadpool.toml
"""
import argparse
import bisect
import re
import struct

BEGIN = "# --- generated by scripts/find_entry_points.py ---"
END = "# --- end find_entry_points ---"


def parse_range(s):
    a, b = s.split(":")
    return int(a, 0), int(b, 0)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--image", required=True)
    ap.add_argument("--base", required=True, type=lambda s: int(s, 0))
    ap.add_argument("--text", required=True, type=parse_range)
    ap.add_argument("--data", required=True, type=parse_range, action="append")
    ap.add_argument("--pdata", required=True, type=parse_range)
    ap.add_argument("--mapping", required=True, help="XenonRecomp's ppc_func_mapping.cpp")
    ap.add_argument("--switch-tables", required=True)
    ap.add_argument("--config", required=True)
    ap.add_argument("--write", action="store_true", help="update the config (default: report only)")
    args = ap.parse_args()

    img = open(args.image, "rb").read()

    def word(a):
        return struct.unpack_from(">I", img, a - args.base)[0]

    text_lo, text_hi = args.text

    def is_code(v):
        return text_lo <= v < text_hi and v % 4 == 0

    funcs = []
    for a in range(args.pdata[0], args.pdata[1], 8):
        b, f = struct.unpack_from(">II", img, a - args.base)
        if b:
            funcs.append((b, b + ((f >> 8) & 0x3FFFFF) * 4))
    funcs.sort()
    starts = [f[0] for f in funcs]

    cfg = open(args.config).read()
    configured = set()
    if BEGIN in cfg:
        configured = {int(x, 16) for x in re.findall(r"0x([0-9A-F]+),", cfg.split(BEGIN)[1].split(END)[0])}
    fnstarts = {int(x, 16) for x in re.findall(r"\{ 0x([0-9A-F]+),", open(args.mapping).read())} - configured
    labels = {int(x, 16) for x in re.findall(r"^\s+0x([0-9A-F]+),", open(args.switch_tables).read(), re.M)}

    refs = {}
    for lo, hi in args.data:
        for a in range(lo, hi, 4):
            v = word(a)
            if is_code(v):
                refs.setdefault(v, set()).add("data")

    # lis rD,hi ; ... addi/ori rX,rD,lo within the next 8 instructions
    for a in range(text_lo, text_hi, 4):
        w = word(a)
        if w >> 26 != 15 or (w >> 16) & 31 != 0:
            continue
        rd = (w >> 21) & 31
        hi = (w & 0xFFFF) << 16
        for b in range(a + 4, min(a + 36, text_hi), 4):
            x = word(b)
            op = x >> 26
            if op in (14, 24) and (x >> 16) & 31 == rd:  # addi / ori with rA = rD
                lo = x & 0xFFFF
                v = (hi + (lo - 0x10000 if op == 14 and lo & 0x8000 else lo)) & 0xFFFFFFFF
                if is_code(v):
                    refs.setdefault(v, set()).add("code")
                break
            if (x >> 21) & 31 == rd and op not in (36, 37, 32, 33):  # rD overwritten (not a store/load into it)
                break

    def entry_like(v):
        p = word(v - 4)
        return p == 0x4E800020 or p == 0 or (p >> 26 == 18 and p & 3 == 0)

    cand = sorted(v for v in refs if v not in fnstarts and v not in labels and entry_like(v))
    lines = []
    for v in cand:
        i = bisect.bisect_right(starts, v) - 1
        inside = i >= 0 and funcs[i][0] <= v < funcs[i][1]
        note = f"in .pdata fn 0x{funcs[i][0]:08X}" if inside else "leaf code"
        lines.append(f"    0x{v:08X},  # referenced from {'+'.join(sorted(refs[v]))}; {note}")
    print(f"{len(refs)} referenced code addresses; {len(cand)} entry-like and not function starts")
    print("\n".join(lines))

    if args.write:
        block = "\n".join([BEGIN,
                           "# Secondary entry points: code addresses the game reaches through pointers that lie",
                           "# inside another function. Do not edit by hand; rerun the tool.",
                           "secondary_entries = ["] + lines + ["]", END])
        if BEGIN in cfg:
            pre, rest = cfg.split(BEGIN, 1)
            cfg = pre + block + rest.split(END, 1)[1]
        else:
            cfg = cfg.replace("\ninvalid_instructions", "\n" + block + "\n\ninvalid_instructions", 1)
        open(args.config, "w").write(cfg)
        print(f"wrote {args.config}")


if __name__ == "__main__":
    main()
