#!/usr/bin/env python3
"""Write runtime/kernel/import_stubs.cpp: a logging stub for every kernel/XAM import the
recompiled code references that the runtime doesn't implement yet, plus a report.

Adapted from SpeedBreaker's scripts/gen_import_stubs.py. Import names come from XenonRecomp's
ppc_recomp_shared.h; an import counts as implemented if another runtime source defines it with
PPC_FUNC, GUEST_FUNCTION_HOOK or GUEST_FUNCTION_STUB. The library of each import comes from
XenonRecomp's export tables (xam_table.inc, xboxkrnl_table.inc). Standard library only:

    python3 -I scripts/gen_import_stubs.py --shared ppc/ppc_recomp_shared.h \
        --runtime runtime --report docs/imports
"""
import argparse
import json
import pathlib
import re


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--shared", required=True, help="XenonRecomp's ppc_recomp_shared.h")
    ap.add_argument("--runtime", required=True, help="runtime source folder")
    ap.add_argument("--tables", default=str(pathlib.Path(__file__).resolve().parent.parent / "tools/XenonRecomp/XenonUtils/xbox"),
                    help="folder with XenonRecomp's xam_table.inc and xboxkrnl_table.inc (for each import's library)")
    ap.add_argument("--report", required=True, help="path without extension for .json/.md")
    args = ap.parse_args()

    runtime = pathlib.Path(args.runtime)
    out = runtime / "kernel" / "import_stubs.cpp"
    imports = sorted(set(re.findall(r"PPC_EXTERN_FUNC\(__imp__(\w+)\)", pathlib.Path(args.shared).read_text())))
    implemented = set()
    for src in runtime.rglob("*.cpp"):
        if src == out:
            continue
        implemented |= set(re.findall(r"(?:PPC_FUNC|GUEST_FUNCTION_HOOK|GUEST_FUNCTION_STUB)\(\s*__imp__(\w+)",
                                      src.read_text(errors="replace")))

    library = {}
    for lib in ("xam", "xboxkrnl"):
        table = pathlib.Path(args.tables) / f"{lib}_table.inc"
        for name in re.findall(r"XE_EXPORT\(\w+,\s*\w+,\s*(\w+),", table.read_text(errors="replace")):
            library.setdefault(name, lib)

    missing = [n for n in imports if n not in implemented]
    lines = [
        "// Generated by scripts/gen_import_stubs.py. Do not edit; implement the import",
        "// elsewhere in runtime/ and rerun the tool.",
        "// Adapted from SpeedBreaker. GPL-3.0-or-later (see COPYING).",
        f"// {len(imports)} imports: {len(imports) - len(missing)} implemented, {len(missing)} stubbed.",
        '#include "../stdafx.h"',
        '#include "unimplemented.h"',
        "",
    ]
    lines += [f'PPC_FUNC(__imp__{n}) {{ UnimplementedImport("{n}", ctx, base); }}' for n in missing]
    out.write_text("\n".join(lines) + "\n")

    by_lib = {}
    for n in imports:
        by_lib.setdefault(library.get(n, "?"), {"implemented": [], "stubbed": []})[
            "stubbed" if n in missing else "implemented"].append(n)
    pathlib.Path(args.report + ".json").write_text(json.dumps(by_lib, indent=2))
    md = ["# Imports: implemented by the runtime vs stubbed", "",
          f"{len(imports)} imports referenced by the recompiled code: "
          f"{len(imports) - len(missing)} implemented, {len(missing)} stubbed (log and return 0).", ""]
    for lib_name, d in sorted(by_lib.items()):
        md += [f"## {lib_name}: {len(d['implemented'])} implemented, {len(d['stubbed'])} stubbed", "",
               "Stubbed: " + (", ".join(f"`{n}`" for n in d["stubbed"]) or "none"), ""]
    pathlib.Path(args.report + ".md").write_text("\n".join(md))
    print(f"{out}: {len(imports)} imports, {len(imports) - len(missing)} implemented, {len(missing)} stubbed")
    for lib_name, d in sorted(by_lib.items()):
        print(f"  {lib_name}: {len(d['implemented'])} implemented, {len(d['stubbed'])} stubbed")


if __name__ == "__main__":
    main()
